const LANG_KEY = "madwatches-lang";

// Saved choice → otherwise Arabic if the browser is Arabic → otherwise English
function detectLanguage() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === "ar" || saved === "en") return saved;
  } catch (err) { /* storage blocked */ }
  return /^ar\b/i.test(navigator.language || "") ? "ar" : "en";
}

let currentLang = detectLanguage();

// t("common.added", { name: "Explorer" }) → "Explorer added to cart"
function t(key, vars) {
  let text = TRANSLATIONS[currentLang][key];
  if (text === undefined) text = TRANSLATIONS.en[key];
  if (text === undefined) return key;
  if (vars) {
    Object.keys(vars).forEach((name) => {
      text = text.split("{" + name + "}").join(vars[name]);
    });
  }
  return text;
}

// The Arabic version of a data field when Arabic is on:
// localized(product, "name") → product.name_ar (if it exists) or product.name
function localized(item, field) {
  if (!item) return "";
  if (currentLang === "ar" && item[field + "_ar"]) return item[field + "_ar"];
  return item[field] || "";
}

// "3 watches" / "3 ساعات" (Arabic has different plural forms)
function countLabel(n, unit) {
  if (currentLang === "ar") {
    const words = {
      watch:  ["ساعة واحدة", "ساعتان", "ساعات", "ساعة"],
      item:   ["قطعة واحدة", "قطعتان", "قطع", "قطعة"]
    }[unit || "watch"];
    if (n === 1) return words[0];
    if (n === 2) return words[1];
    if (n >= 3 && n <= 10) return n + " " + words[2];
    return n + " " + words[3];
  }
  const en = { watch: ["watch", "watches"], item: ["item", "items"] }[unit || "watch"];
  return n + " " + (n === 1 ? en[0] : en[1]);
}

// Fills every [data-i18n] and [data-i18n-attr] inside `root`
function translatePage(root) {
  root = root || document;
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  // data-i18n-attr="aria-label:nav.cart, placeholder:search.placeholder"
  root.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    el.dataset.i18nAttr.split(",").forEach((pair) => {
      const parts = pair.split(":");
      if (parts.length === 2) el.setAttribute(parts[0].trim(), t(parts[1].trim()));
    });
  });
}

// Sets <html lang/dir>, translates the page and tells every script
// to re-draw its content (they listen for the "languagechange" event).
function setLanguage(lang, save) {
  currentLang = lang === "ar" ? "ar" : "en";
  if (save) {
    try { localStorage.setItem(LANG_KEY, currentLang); } catch (err) { /* ignore */ }
  }
  const html = document.documentElement;
  html.lang = currentLang;
  html.dir = currentLang === "ar" ? "rtl" : "ltr";
  translatePage(document);
  document.querySelectorAll("[data-set-lang]").forEach((btn) => {
    btn.setAttribute("aria-pressed", btn.dataset.setLang === currentLang);
  });
  document.dispatchEvent(new CustomEvent("languagechange", { detail: currentLang }));
}

